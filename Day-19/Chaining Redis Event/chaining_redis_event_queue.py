"""### Step 9: Add Retry Decorator"""

from functools import wraps
import time

def retry(
        retries=3,
        delay=1
):

    def decorator(func):

        @wraps(func)
        def wrapper(*args, **kwargs):

            for attempt in range(retries):

                try:
                    return func(
                        *args,
                        **kwargs
                    )

                except Exception as e:

                    print(
                        f"Retry {attempt+1}"
                    )

                    time.sleep(delay)

            raise Exception(
                "Max retries exceeded"
            )

        return wrapper

    return decorator

