def search_kb(query):

    query_vector = model_embed.encode(
        [query]
    )

    D, I = index.search(
        np.array(query_vector).astype("float32"),
        2
    )

    results = [
        support_docs[i]
        for i in I[0]
    ]

    return "\n".join(results)

